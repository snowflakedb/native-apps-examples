CREATE ROLE IF NOT EXISTS WAREHOUSE_WHISPERER_EXECUTOR;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE WAREHOUSE_WHISPERER_EXECUTOR;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE WAREHOUSE_WHISPERER_EXECUTOR;

CREATE DATABASE IF NOT EXISTS WAREHOUSE_WHISPERER_PROVIDER;
GRANT OWNERSHIP ON DATABASE WAREHOUSE_WHISPERER_PROVIDER
  TO ROLE WAREHOUSE_WHISPERER_EXECUTOR COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA WAREHOUSE_WHISPERER_PROVIDER.PUBLIC
  TO ROLE WAREHOUSE_WHISPERER_EXECUTOR COPY CURRENT GRANTS;

CREATE WAREHOUSE IF NOT EXISTS WAREHOUSE_WHISPERER_BUILD_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;
GRANT OWNERSHIP ON WAREHOUSE WAREHOUSE_WHISPERER_BUILD_WH
  TO ROLE WAREHOUSE_WHISPERER_EXECUTOR COPY CURRENT GRANTS;

GRANT ROLE WAREHOUSE_WHISPERER_EXECUTOR TO USER IDENTIFIER(CURRENT_USER());
